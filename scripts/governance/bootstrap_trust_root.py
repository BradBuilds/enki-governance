#!/usr/bin/env python3
"""
Bootstrap the Tier-R trust root for this server.

Run this ONCE on node-A (or any sovereign install) to:
  1. Generate (or load) the software root signing key
  2. Issue the self-signed Tier-R DeviceGrant
  3. Save the R grant to the grants directory
  4. Write /etc/enki/trusted_keys.signed listing R's pubkey

After this completes, run scripts/key_ceremony.py (in the
enki-hardware-key repo) to provision a Tier-K HWKEY whose grant
chains back to this R.

Usage:
    python scripts/governance/bootstrap_trust_root.py
    python scripts/governance/bootstrap_trust_root.py --device-id node1-root --comment "node-A production root"
    python scripts/governance/bootstrap_trust_root.py --force-genesis  # overwrite existing trust root

Environment:
    ENKI_ROOT_PASSWORD          required, password for root key file encryption
    ENKI_ROOT_KEY_PATH          default storage/keys/root_key.enc
    ENKI_GRANTS_DIR             default storage/grants
    ENKI_TRUSTED_KEYS_PATH      default /etc/enki/trusted_keys.signed
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

# Project root on import path
_PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(_PROJECT_ROOT))

from storage.auth.config import GRANTS_DIR, ROOT_KEY_PATH
from storage.auth.grant import issue_root_grant
from storage.auth.grant_store import GrantStore
from storage.auth.root_key import generate_root_key, load_root_key


DEFAULT_TRUSTED_KEYS_PATH = "/etc/enki/trusted_keys.signed"


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _read_trust_root(path: Path) -> dict | None:
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None


def _write_trust_root(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Bootstrap the Tier-R trust root for this server.",
    )
    parser.add_argument("--device-id", default="enki-root",
                        help="device_id for the Tier-R grant (default: enki-root)")
    parser.add_argument("--tenant", default="default",
                        help="Tenant scope on the R grant (default: default)")
    parser.add_argument("--expires-days", type=int, default=3650,
                        help="R grant expiry in days (default: 10y)")
    parser.add_argument("--comment", default="Software Tier R generated by bootstrap_trust_root.py",
                        help="Comment recorded in trusted_keys.signed")
    parser.add_argument("--trusted-keys-path",
                        default=os.environ.get("ENKI_TRUSTED_KEYS_PATH", DEFAULT_TRUSTED_KEYS_PATH),
                        help="Output path for trusted_keys.signed")
    parser.add_argument("--force-genesis", action="store_true",
                        help="Overwrite an existing trusted_keys.signed (DANGEROUS)")
    args = parser.parse_args()

    print()
    print("  ┌─────────────────────────────────────────────────────┐")
    print("  │      ENKI TRUST ROOT BOOTSTRAP — Tier R genesis     │")
    print("  └─────────────────────────────────────────────────────┘")
    print()

    root_password = os.environ.get("ENKI_ROOT_PASSWORD")
    if not root_password:
        print("  ERROR: ENKI_ROOT_PASSWORD not set.", file=sys.stderr)
        return 1

    trusted_keys_path = Path(args.trusted_keys_path)
    existing = _read_trust_root(trusted_keys_path)

    if existing and not args.force_genesis:
        roots = existing.get("trusted_root_pubkeys", [])
        print(f"  Trust root already exists at {trusted_keys_path}")
        print(f"  Trusted Tier-R pubkeys: {len(roots)}")
        for r in roots:
            print(f"    - {r.get('device_id', '?')}  tier={r.get('tier')}  "
                  f"key={r.get('public_key', '')[:24]}...")
        print()
        print("  Refusing to overwrite. Use --force-genesis if you really mean to.")
        return 0

    # ── Step 1: Root key (load or generate) ─────────────────────────
    print(f"  [1/4] Loading root signing key ({ROOT_KEY_PATH})...")
    key_path = Path(ROOT_KEY_PATH)
    if key_path.exists():
        root_key = load_root_key(str(key_path), root_password)
        print("        Existing root key loaded.")
    else:
        key_path.parent.mkdir(parents=True, exist_ok=True)
        root_key = generate_root_key(str(key_path), root_password)
        print("        New root key generated.")
    root_pub_b64 = root_key.public_key_base64()
    print(f"        Public key: {root_pub_b64}")

    # ── Step 2: Self-signed Tier-R grant ────────────────────────────
    print(f"  [2/4] Issuing self-signed Tier-R DeviceGrant...")
    expires = (datetime.now(timezone.utc) + timedelta(days=args.expires_days)).isoformat()
    r_grant = issue_root_grant(
        device_id=args.device_id,
        public_key_bytes=root_key.public_key_bytes_raw(),
        root_key=root_key,
        expires_at=expires,
        tenant_scopes=[args.tenant],
    )
    print(f"        grant_id:   {r_grant.grant_id}")
    print(f"        device_id:  {r_grant.device_id}")
    print(f"        tier:       R  (self-signed)")
    print(f"        expires:    {expires[:10]}")

    # ── Step 3: Save the R grant ────────────────────────────────────
    print(f"  [3/4] Saving R grant to {GRANTS_DIR}/...")
    store = GrantStore(GRANTS_DIR)
    store.save(r_grant)
    print(f"        {GRANTS_DIR}/{r_grant.device_id}.json")

    # ── Step 4: Write trusted_keys.signed ───────────────────────────
    print(f"  [4/4] Writing trust root to {trusted_keys_path}...")
    payload = {
        "version": "1.0.0",
        "created_at": _now_iso(),
        "trusted_root_pubkeys": [
            {
                "device_id": r_grant.device_id,
                "tier": "R",
                "public_key": r_grant.public_key,
                "grant_id": r_grant.grant_id,
                "comment": args.comment,
            }
        ],
    }
    try:
        _write_trust_root(trusted_keys_path, payload)
    except PermissionError as e:
        print(f"        PermissionError: {e}", file=sys.stderr)
        print(f"        Re-run with sudo, or set ENKI_TRUSTED_KEYS_PATH to a writable location.",
              file=sys.stderr)
        return 1
    print(f"        OK")

    print()
    print("  ═════════════════════════════════════════════════════════")
    print("  Trust root established.")
    print()
    print("  Next: provision a Tier K HWKEY (run on a host with the watch attached):")
    print()
    print("    cd ../enki-hardware-key")
    print("    python -m server.key_ceremony \\")
    print(f"      --device-id node1-HWKEY \\")
    print(f"      --r-grant {GRANTS_DIR}/{r_grant.device_id}.json")
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
