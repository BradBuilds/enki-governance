-- LDU-T: Raw truth storage (extended for signal source types)
-- The existing ldu_t_entries table structure is preserved in the LDU-T adapter.
-- This table stores raw signal bytes for the command center pipeline.
CREATE TABLE IF NOT EXISTS ldu_t_signals (
    rid             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ldu_t_id        VARCHAR(255) NOT NULL UNIQUE,      -- ldu_t_<node>_<ts>_<rand>
    tenant_id       VARCHAR(255) NOT NULL,
    node_id         VARCHAR(255) NOT NULL,             -- FD-2
    device_id       VARCHAR(255) NOT NULL,
    source_type     VARCHAR(100) NOT NULL,             -- tak_cot, email, sensor, etc.
    raw_bytes       BYTEA NOT NULL,                    -- original payload, never modified
    raw_sha256      VARCHAR(64) NOT NULL,              -- content hash of raw bytes
    raw_byte_length BIGINT NOT NULL,
    content_type    VARCHAR(255),                      -- MIME type hint from request
    format_detected VARCHAR(100),                      -- auto-detection result
    detection_confidence DOUBLE PRECISION,             -- 0.0-1.0
    receipt_id      VARCHAR(255),
    ingestion_timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(tenant_id, raw_sha256)                     -- dedup: same bytes = same entry
);
CREATE INDEX IF NOT EXISTS idx_ldu_t_signals_tenant
    ON ldu_t_signals(tenant_id);
CREATE INDEX IF NOT EXISTS idx_ldu_t_signals_device
    ON ldu_t_signals(device_id);

-- Signals: Normalized signals (LDU-W level)
CREATE TABLE IF NOT EXISTS signals (
    rid             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signal_id       VARCHAR(255) NOT NULL UNIQUE,      -- sig_<node>_<ts>_<rand>
    tenant_id       VARCHAR(255) NOT NULL,
    node_id         VARCHAR(255) NOT NULL,             -- FD-2: which node stored this
    device_id       VARCHAR(255) NOT NULL,
    identity_id     VARCHAR(255),                      -- who/what generated it
    signal_type     VARCHAR(255) NOT NULL,             -- from GDU vocabulary
    source_domain   VARCHAR(100) NOT NULL,             -- tak_cot, email, sensor, etc.
    severity        VARCHAR(20) NOT NULL DEFAULT 'informational',
    confidence      VARCHAR(20) NOT NULL DEFAULT 'confirmed',
    timestamp       TIMESTAMPTZ NOT NULL,              -- event time (from source)
    server_time     TIMESTAMPTZ NOT NULL DEFAULT NOW(),-- when server received it
    -- Geospatial (nullable) — PostGIS location column added via ALTER TABLE below
    latitude        DOUBLE PRECISION,
    longitude       DOUBLE PRECISION,
    altitude        DOUBLE PRECISION,
    accuracy        DOUBLE PRECISION,                  -- meters
    payload         JSONB NOT NULL,                    -- full parsed signal content
    observables     JSONB DEFAULT '[]',                -- extracted observables summary
    metadata        JSONB DEFAULT '{}',                -- parser/profile metadata
    ldu_t_id        VARCHAR(255) NOT NULL,             -- lineage to raw LDU-T entry
    ldu_p_id        VARCHAR(255),                      -- lineage to LDU-P if provisioned
    cid             VARCHAR(64) NOT NULL,              -- content hash (SHA-256)
    receipt_rid     BIGINT,                            -- link to signal_receipts batch
    origin_node_id  VARCHAR(255) NOT NULL,             -- FD-2: where signal originated
    federation_id   VARCHAR(255),                      -- which agreement authorized sharing
    route_path      TEXT[] DEFAULT '{}',               -- node_ids this signal traversed
    device_signature VARCHAR(255),                      -- Ed25519 sig from source device
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_signals_tenant_type
    ON signals(tenant_id, signal_type);
CREATE INDEX IF NOT EXISTS idx_signals_tenant_time
    ON signals(tenant_id, timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_signals_device
    ON signals(device_id);
CREATE INDEX IF NOT EXISTS idx_signals_identity
    ON signals(identity_id);
CREATE INDEX IF NOT EXISTS idx_signals_ldu_t
    ON signals(ldu_t_id);
CREATE INDEX IF NOT EXISTS idx_signals_node
    ON signals(node_id);
CREATE INDEX IF NOT EXISTS idx_signals_origin
    ON signals(origin_node_id)
    WHERE origin_node_id != node_id;  -- only index federated signals
CREATE INDEX IF NOT EXISTS idx_signals_cid
    ON signals(tenant_id, cid);

-- PostGIS location column (auto-populated from lat/lon on INSERT)
ALTER TABLE signals ADD COLUMN IF NOT EXISTS location GEOMETRY(Point, 4326);
CREATE INDEX IF NOT EXISTS idx_signals_location ON signals USING GIST(location);

CREATE OR REPLACE FUNCTION populate_signal_location()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.latitude IS NOT NULL AND NEW.longitude IS NOT NULL AND NEW.location IS NULL THEN
        NEW.location := ST_SetSRID(ST_MakePoint(NEW.longitude, NEW.latitude), 4326);
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS auto_populate_location ON signals;
CREATE TRIGGER auto_populate_location
    BEFORE INSERT ON signals
    FOR EACH ROW EXECUTE FUNCTION populate_signal_location();

