-- ─────────────────────────────────────────────────────────────────────────────
-- APPEND-ONLY ENFORCEMENT (triggers)
-- ─────────────────────────────────────────────────────────────────────────────
-- These triggers prevent UPDATE/DELETE on append-only ledger tables.
-- The enki_db PostgreSQL user should also have restricted privileges,
-- but triggers are defense-in-depth.

CREATE OR REPLACE FUNCTION prevent_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'Mutation denied: % on append-only table %',
        TG_OP, TG_TABLE_NAME;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

