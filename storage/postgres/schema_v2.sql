-- ─────────────────────────────────────────────────────────────────────────────
-- Z. RESEARCH GOVERNOR (slow-burn self-expanding topic research)
-- ─────────────────────────────────────────────────────────────────────────────
-- Each row is a research job: one entity to investigate. The governor picks
-- the highest-priority pending job, researches it (Wikidata, SEC, GDELT, etc.),
-- discovers connections, and queues those connections at depth+1. Processing
-- is single-threaded and paced (~1 entity per 75 seconds) so it never spikes
-- system resources or API rate limits.

CREATE TABLE IF NOT EXISTS research_queue (
    job_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id        VARCHAR(255) NOT NULL,
    tenant_id       VARCHAR(255) NOT NULL,
    entity_name     VARCHAR(500) NOT NULL,
    entity_type     VARCHAR(50) NOT NULL,           -- person, organization, location
    depth           INTEGER NOT NULL DEFAULT 0,     -- 0=seed, 1=discovered, 2=discovered-from-discovered
    priority        INTEGER NOT NULL DEFAULT 100,   -- lower=higher; seeds=0, discovered=(depth)*100
    status          VARCHAR(20) NOT NULL DEFAULT 'pending',  -- pending, running, complete, failed, skipped
    discovered_from VARCHAR(500),                   -- parent entity name that led to this
    discovered_via  VARCHAR(100),                   -- wikidata_career, sec_officers, wikidata_family, etc.
    result_summary  JSONB DEFAULT '{}',             -- {data_sources, connections_found, nodes_created, edges_created}
    error           TEXT,
    attempts        INTEGER DEFAULT 0,
    max_depth       INTEGER NOT NULL DEFAULT 3,
    contact_id      VARCHAR(255),                   -- auto-created contact ID
    started_at      TIMESTAMPTZ,
    completed_at    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_rq_topic ON research_queue(topic_id, status);
CREATE INDEX IF NOT EXISTS idx_rq_pending ON research_queue(topic_id, status, priority, created_at)
    WHERE status = 'pending';
CREATE UNIQUE INDEX IF NOT EXISTS idx_rq_dedup
    ON research_queue(topic_id, LOWER(entity_name), entity_type)
    WHERE status NOT IN ('skipped', 'failed');

