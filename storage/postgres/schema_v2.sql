    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'refpoints_geo_trigger') THEN
        CREATE TRIGGER refpoints_geo_trigger BEFORE INSERT OR UPDATE OF latitude, longitude ON reference_points FOR EACH ROW EXECUTE FUNCTION auto_update_location();
    END IF;
END $$;

