-- Thread ↔ Knowledge node links (which nodes were produced by which thread)
-- relevance controls how the node participates in thread context:
--   pinned   — always included in AI context, shown prominently
--   active   — normal weight, included in context (default)
--   dimmed   — still linked but deprioritized in AI context (low weight)
--   unlinked — removed from this thread's view/context, node still exists in project graph
CREATE TABLE IF NOT EXISTS thread_nodes (
    thread_id       VARCHAR(255) NOT NULL REFERENCES chat_threads(thread_id) ON DELETE CASCADE,
    node_id         VARCHAR(255) NOT NULL,
    message_rid     BIGINT,                              -- which message produced it
    auto_generated  BOOLEAN NOT NULL DEFAULT TRUE,       -- AI-produced vs user-confirmed
    relevance       VARCHAR(20) NOT NULL DEFAULT 'active', -- pinned, active, dimmed, unlinked
    user_note       TEXT,                                 -- why this was pinned/dimmed/unlinked
    position_x      DOUBLE PRECISION,                    -- user-arranged position in thread graph
    position_y      DOUBLE PRECISION,
    -- Contextual scoring (per-thread assessment of this node)
    context_confidence      DOUBLE PRECISION,             -- confidence of this node IN THIS THREAD'S context
    context_status          VARCHAR(20),                  -- confirmed, supported, contested, unverified, stale
    context_evidence        JSONB DEFAULT '{}',           -- full evidence profile for this context
    context_contradictions  INT DEFAULT 0,                -- contradictions relevant to this thread
    context_corroborations  INT DEFAULT 0,                -- corroborations relevant to this thread
    context_gaps            TEXT[] DEFAULT '{}',           -- gaps that matter in this thread
    context_scored_at       TIMESTAMPTZ,                  -- when context scoring last ran
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (thread_id, node_id)
);
CREATE INDEX IF NOT EXISTS idx_thread_nodes_node ON thread_nodes(node_id);
CREATE INDEX IF NOT EXISTS idx_thread_nodes_relevance ON thread_nodes(thread_id, relevance)
    WHERE relevance != 'unlinked';


